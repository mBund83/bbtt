const BB_LANG_KEY = "bb_lang";

function getLang() {
  const stored = localStorage.getItem(BB_LANG_KEY);
  if (stored === "en" || stored === "no") return stored;
  return "no";
}

function setLang(lang) {
  localStorage.setItem(BB_LANG_KEY, lang);
  document.documentElement.lang = lang === "en" ? "en" : "no";
}

function t(key, vars) {
  const lang = getLang();
  const table = window.BB_I18N[lang] || window.BB_I18N.no;
  let value = table[key] ?? window.BB_I18N.no[key] ?? key;
  if (vars) {
    Object.keys(vars).forEach((k) => {
      value = value.replace(new RegExp(`\\{${k}\\}`, "g"), String(vars[k]));
    });
  }
  return value;
}

function applyI18n() {
  const lang = getLang();
  setLang(lang);

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (!key) return;
    el.textContent = t(key);
  });

  document.querySelectorAll("[data-i18n-html]").forEach((el) => {
    const key = el.getAttribute("data-i18n-html");
    if (!key) return;
    el.innerHTML = t(key);
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const key = el.getAttribute("data-i18n-placeholder");
    if (!key) return;
    el.setAttribute("placeholder", t(key));
  });

  document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    const key = el.getAttribute("data-i18n-aria");
    if (!key) return;
    el.setAttribute("aria-label", t(key));
  });

  const metaDesc = document.querySelector('meta[name="description"]');
  if (metaDesc && metaDesc.hasAttribute("data-i18n-content")) {
    metaDesc.setAttribute("content", t(metaDesc.getAttribute("data-i18n-content")));
  }

  if (document.body.dataset.page === "sales") {
    document.title = t("sales.metaTitle");
  }

  document.querySelectorAll("[data-lang-toggle]").forEach((btn) => {
    const next = lang === "no" ? "en" : "no";
    btn.setAttribute("aria-label", t("lang.aria"));
    btn.dataset.nextLang = next;
    const label = btn.querySelector("[data-lang-label]");
    if (label) label.textContent = t("lang.switch");
    const flag = btn.querySelector("[data-lang-flag]");
    if (flag) flag.textContent = next === "en" ? "🇬🇧" : "🇳🇴";
  });

  document.dispatchEvent(new CustomEvent("bb:langchange", { detail: { lang } }));
}

function initI18n() {
  document.querySelectorAll("[data-lang-toggle]").forEach((btn) => {
    btn.addEventListener("click", () => {
      const next = btn.dataset.nextLang || (getLang() === "no" ? "en" : "no");
      setLang(next);
      applyI18n();
    });
  });
  applyI18n();
}

document.addEventListener("DOMContentLoaded", initI18n);
